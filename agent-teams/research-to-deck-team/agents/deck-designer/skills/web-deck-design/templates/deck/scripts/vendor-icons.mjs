// Copies the line icons index.html uses (<i data-icon="name">) from an unpacked lucide-static package into
// assets/icons.js, so the deck works offline. Lucide is ISC-licensed; its licence is copied too.
// Usage: npm pack lucide-static && tar -xzf lucide-static-*.tgz   then   node scripts/vendor-icons.mjs ./package
import { readFileSync, writeFileSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = process.argv[2];
if (!pkg) { console.error('Usage: node scripts/vendor-icons.mjs <unpacked lucide-static package>'); process.exit(1); }

const html = readFileSync(join(root, 'index.html'), 'utf8');
const names = [...new Set([...html.matchAll(/data-icon="([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();
const out = {};
const missing = [];
for (const n of names) {
  const file = join(pkg, 'icons', `${n}.svg`);
  if (!existsSync(file)) { missing.push(n); continue; }
  const svg = readFileSync(file, 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
const version = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version;
writeFileSync(join(root, 'assets', 'icons.js'),
  `// Lucide icons (ISC licence, see LUCIDE-LICENSE.txt), lucide-static ${version}. Generated by scripts/vendor-icons.mjs.\n` +
  `window.DECK_ICONS = ${JSON.stringify(out, null, 1)};\n`);
const licence = ['LICENSE', 'LICENSE.txt', 'license'].map((f) => join(pkg, f)).find(existsSync);
if (licence) copyFileSync(licence, join(root, 'assets', 'LUCIDE-LICENSE.txt'));
console.log(`${Object.keys(out).length} icons written${missing.length ? '; not found: ' + missing.join(', ') : ''}`);
if (missing.length) process.exit(2);
